import { describe, expect, it } from "vitest";
import fs from "node:fs";
import path from "node:path";

describe("Care Labels admin contracts", () => {
  const root = path.resolve(process.cwd());
  it("is linked from the existing Operations dashboard instead of a separate password area", () => {
    const operations = fs.readFileSync(path.join(root, "client/src/pages/OperationsDashboard.tsx"), "utf8");
    expect(operations).toContain('href="/care-labels/admin"');
    const admin = fs.readFileSync(path.join(root, "client/src/pages/CareLabelAdmin.tsx"), "utf8");
    expect(admin).toContain("trpc.careLabels.admin.useQuery");
    expect(admin).toContain("trpc.careLabels.updatePrivatePrice.useMutation");
    expect(admin).toContain('accept="image/svg+xml,image/png,image/jpeg,image/webp"');
    expect(admin).toContain("LESOUL_QR_PNG_SVG_FINAL_779a7da5.zip");
    expect(admin).toContain("LESOUL_QR_CARDS_CHINESE_c0bb0b21.pdf");
    expect(admin).toContain("QR_MATCHING_b8c78314.xlsx");
    expect(admin).toContain('href="/care-labels/print"');
    expect(admin).toContain("CARE_LABEL_STANDARDS");
    expect(admin).toContain("CARE_LABEL_MATERIALS");
    expect(admin).toContain("toggleMaterial");
    expect(admin).toContain("CARE_LABEL_PUBLIC_FIELD_OPTIONS");
    expect(admin).toContain("상품명·分类·材质");
    expect(admin).toContain("selectStandard");
    expect(admin).toContain("selectSafety");
    expect(admin).toContain("selectGrade");
    expect(admin).toContain("editStructuredText");
    expect(admin).toContain("normalizeSearchText");
    expect(admin).toContain("normalize(\"NFKC\")");
    expect(admin).toContain("row.data.origin");
    expect(admin).toContain("row.data.dealer");
    expect(admin).toContain("createProduct");
    expect(admin).toContain("addProductFromTemplate");
    expect(admin).toContain('name: ""');
    expect(admin).toContain('dealer: "市南区乐搜商行"');
    expect(admin).toContain('size: ""');
    expect(admin).toContain("添加新商品");
    expect(admin).toContain("materialCompositionText");
    expect(admin).toContain('composition: materialCompositionText(next)');
    expect(admin).toContain('composition: draft.composition || materialCompositionText(materials)');
    expect(admin).toContain('standard: draft.standard || standard?.nameZh || ""');
    expect(admin).toContain('safety: draft.safety || safety?.nameZh || ""');
    expect(admin).toContain('grade: draft.grade || grade?.nameZh || ""');
    expect(admin).toContain("进口商或经销商名称 / Importer or Distributor");
    expect(admin).toContain('dealer: "市南区乐搜商行"');
    expect(admin).toContain("QR 공개 화면에서는 이 값이 进口商或经销商名称으로 표시됩니다.");
    expect(admin).toContain('placeholder={key === "dealer" ? "进口商或经销商名称" : undefined}');
    expect(admin).toContain('const standard = standardOptions.find');
    expect(admin).toContain('addCustomStandard');
    expect(admin).toContain('removeCustomStandard');
    expect(admin).toContain('standards: customStandards.map');
    expect(admin).toContain("CARE_LABEL_MATERIALS.map((option)");
    expect(admin).toContain('min="0" max="100"');
    expect(admin).toContain("재질 함량 합계는 반드시 100%여야 합니다.");
    expect(admin).not.toContain('["lining", "里料 / Lining"]');
    expect(admin).not.toContain('["filling", "填充物 / Filling"]');
  });
});
