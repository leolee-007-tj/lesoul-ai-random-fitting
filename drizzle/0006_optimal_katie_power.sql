CREATE TABLE `generationLogs` (
	`id` int AUTO_INCREMENT NOT NULL,
	`requestId` varchar(96) NOT NULL,
	`retryOfRequestId` varchar(96),
	`retryCount` int NOT NULL DEFAULT 0,
	`userImageUrl` text NOT NULL,
	`poseId` int NOT NULL,
	`style` varchar(80) NOT NULL,
	`productIds` json NOT NULL,
	`backgroundId` int NOT NULL,
	`provider` varchar(80) NOT NULL,
	`status` enum('preparing','generating','completed','fallback','failed') NOT NULL DEFAULT 'preparing',
	`resultImageUrl` text,
	`errorMessage` text,
	`durationMs` int,
	`validationStatus` enum('not_enabled','pending','passed','acceptable','retry_recommended','failed') NOT NULL DEFAULT 'not_enabled',
	`garmentPreservationScore` int,
	`identityPreservationScore` int,
	`overallQualityScore` int,
	`validationDetails` json,
	`startedAt` timestamp NOT NULL DEFAULT (now()),
	`completedAt` timestamp,
	`createdAt` timestamp NOT NULL DEFAULT (now()),
	`updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `generationLogs_id` PRIMARY KEY(`id`),
	CONSTRAINT `generationLogs_requestId_unique` UNIQUE(`requestId`)
);
